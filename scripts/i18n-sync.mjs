#!/usr/bin/env node
// Browser assets are confined to each plugin's browserRoot. Share the canonical
// reader/translator runtime; locale writes and initialization belong to the app.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import ts from "typescript";

export const runtimeCopies = [
  "pi-web-plugins/files", "pi-web-plugins/git/browser", "pi-web-plugins/info",
  "pi-web-plugins/mermaid", "pi-web-plugins/terminal", "pi-web-plugins/updates",
  "pi-web-plugins/workspace-tasks", "pi-packages/relays", "pi-packages/workflows/browser",
];
const root = new URL("../", import.meta.url);
export async function syncI18nRuntimes(check = false) {
  const source = await readFile(new URL("src/shared/i18nCore.ts", root), "utf8");
  const parsed = ts.createSourceFile("i18nCore.ts", source, ts.ScriptTarget.Latest, true);
  const appFunctions = new Set(["setLocalePreference", "initializeLocale"]);
  let runtime = source;
  for (const statement of [...parsed.statements].reverse()) {
    if (ts.isFunctionDeclaration(statement) && appFunctions.has(statement.name?.text)) {
      runtime = runtime.slice(0, statement.getFullStart()) + runtime.slice(statement.end);
    }
  }
  const generated = "// Generated by scripts/i18n-sync.mjs from src/shared/i18nCore.ts. Do not edit.\n" + runtime;
  const stale = [];
  for (const directory of runtimeCopies) {
    const target = new URL(`${directory}/i18nCore.ts`, root);
    if (check) {
      const actual = await readFile(target, "utf8");
      if (actual !== generated) stale.push(directory);
    } else await writeFile(target, generated);
  }
  if (stale.length > 0) throw new Error(`Outdated locale runtimes: ${stale.join(", ")}. Run node scripts/i18n-sync.mjs.`);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await syncI18nRuntimes(process.argv.includes("--check"));
}
